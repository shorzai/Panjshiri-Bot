import axios from "axios";

export default async function imagine(sock, from, body, m, args) {
    const prompt = args.join(" ").trim();
    
    if (!prompt) {
        return await sock.sendMessage(from, { 
            text: "🎨 *AI Image Generator*\n\nمثال:\n!imagine a cat in space\n!imagine یک شیر در جنگل" 
        }, { quoted: m });
    }

    await sock.sendMessage(from, { text: "🎨 در حال ساخت تصویر با هوش مصنوعی... (ممکن است ۱۰ ثانیه طول بکشد)" }, { quoted: m });

    try {
        // استفاده از سرویس رایگان Pollinations (بدون نیاز به کلید)
        const url = `https://image.pollinations.ai/prompt/${encodeURIComponent(prompt)}?width=1024&height=1024&nologo=true`;
        
        const res = await axios.get(url, { 
            responseType: "arraybuffer", 
            timeout: 45000 
        });
        
        const buffer = Buffer.from(res.data, "binary");

        await sock.sendMessage(from, { 
            image: buffer, 
            caption: `✨ *Prompt:* ${prompt}\n🤖 *Generated by RAEES AI*` 
        }, { quoted: m });

    } catch (error) {
        console.error("IMAGINE ERROR:", error.message);
        await sock.sendMessage(from, { text: "❌ خطا در ساخت تصویر. لطفاً دوباره تلاش کنید." }, { quoted: m });
    }
}
