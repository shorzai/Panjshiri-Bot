import axios from "axios";

export default async function fakechat(sock, from, body, m, args) {
    try {
        const input = args.join(" ");
        if (!input.includes("|")) {
            return await sock.sendMessage(from, { text: "🗣️ *Fake Chat Generator*\n\nUsage:\n!fakechat Name|Message\n\nExample:\n!fakechat Ali|Hello how are you?" }, { quoted: m });
        }

        const [name, message] = input.split("|").map(s => s.trim());
        if (!name || !message) throw new Error("Invalid format");

        await sock.sendMessage(from, { text: "📸 Generating fake chat screenshot..." }, { quoted: m });

        const url = `https://api.popcat.xyz/fakechat?text=${encodeURIComponent(message)}&name=${encodeURIComponent(name)}`;
        const res = await axios.get(url, { responseType: "arraybuffer", timeout: 20000 });

        await sock.sendMessage(from, { 
            image: Buffer.from(res.data, "binary"), 
            caption: `🗣️ *Generated by RAEES SULTAN BOT*` 
        }, { quoted: m });

    } catch (error) {
        await sock.sendMessage(from, { text: "❌ Error generating fake chat." }, { quoted: m });
    }
}
