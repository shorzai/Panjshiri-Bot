import axios from "axios";

export default async function carbon(sock, from, body, m, args) {
    try {
        const code = args.join(" ");
        if (!code) {
            return await sock.sendMessage(from, { text: "💻 *Carbon Generator*\n\nUsage:\n!carbon console.log('Hello World');" }, { quoted: m });
        }

        await sock.sendMessage(from, { text: "🎨 Generating beautiful code image..." }, { quoted: m });

        // Free Carbon API
        const url = `https://api.popcat.xyz/carbon?code=${encodeURIComponent(code)}`;
        const res = await axios.get(url, { responseType: "arraybuffer", timeout: 30000 });
        
        const buffer = Buffer.from(res.data, "binary");

        await sock.sendMessage(from, { 
            image: buffer, 
            caption: `💻 *Generated by RAEES SULTAN BOT*` 
        }, { quoted: m });

    } catch (error) {
        console.error("CARBON ERROR:", error.message);
        await sock.sendMessage(from, { text: "❌ Error generating image. Code might be too long." }, { quoted: m });
    }
}
